/** IDs and English source section anchors stay stable in both languages. */
export function localiseHelpPage(page: DocPage, language: PortalLanguage): DocPage {
  const translated = language === 'ja' ? HELP_PAGES_JA[page.id] : undefined
  return translated
    ? {
      ...page,
      title: translated.title,
      summary: translated.summary,
      sections: translated.sections,
    }
    : page
}
